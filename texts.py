# --- шаги расклада ------------------------------------------------------
def draw_prompt(position: str) -> str:
    """Заголовок «Вытяните…» + бейдж текущей позиции."""
    return (f"<b>{_DRAW_TITLES[position]}</b>\n"
            f"{POSITION_LABEL[position]} — {POSITION_DESC[position]}")


def reveal_message(rune: dict, position: str, is_reversed: bool) -> str:
    """Раскрытие руны: позиция, символ, имя, ориентация. Без текста толкования."""
    orientation = "Перевёрнутая позиция" if is_reversed else "Прямая позиция"
    return (
        f"<b>{POSITION_LABEL[position]}</b> — {POSITION_DESC[position]}\n\n"
        f"{rune['symbol']}\n"
        f"<b>{html.escape(rune['nameRu'])}</b>\n"
        f"{html.escape(rune['name'])}\n"
        f"<i>{orientation}</i>"
    )


def result_message(drawn: list[dict]) -> str:
    """Итоговое «Послание Рун»: карточки трёх рун + заключение + футер.

    Каждый элемент drawn: {"rune": dict, "position": str, "is_reversed": bool}.
    Блок «Общее толкование» из приложения не дублируем — тексты уже в карточках.
    """
    parts = [
        "<b>✦ Послание Рун ✦</b>",
        "Три Норны раскрыли вашу судьбу",
        "",
    ]
    for item in drawn:
        rune = item["rune"]
        position = item["position"]
        is_reversed = item["is_reversed"]
        badge = "\n<i>Перевёрнутая</i>" if is_reversed else ""
        parts.append(
            f"<b>{POSITION_LABEL[position]}</b> — {POSITION_DESC[position]}\n"
            f"{rune['symbol']} <b>{html.escape(rune['nameRu'])}</b> "
            f"({html.escape(rune['name'])}){badge}\n"
            f"<i>{html.escape(rune_meaning(rune, is_reversed))}</i>\n"
            f"{html.escape(rune_text(rune, position, is_reversed))}"
        )
        parts.append("")
    parts.append(
        "Руны указывают путь, но выбор всегда за вами. "
        "Прошлое научило, настоящее даёт силу, будущее зависит от ваших решений."
    )
    parts.append("")
    parts.append("Гадание на рунах Старшего Футарка • 24 руны • Расклад «Три Норны»")
    return "\n".join(parts)


